// Suggests where each diagram callout's numbered marker goes: the point of the drawing
// nearest to where the label's text used to sit, nudged beside it so the marker doesn't
// cover the line, and spaced so markers never overlap. Writes
// src/library/callout-positions.js. Review the result by eye (overrides at the bottom
// of this file win). Run: node scripts/place-callouts.mjs  (needs svg-path-properties)
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { DIAG } from '../src/library/content.js';
import { ALL_IDS } from '../src/library/index.js';
import { mergeLabels } from '../src/library/callouts.js';

const require = createRequire(process.env.SVGPP || import.meta.url);
const { svgPathProperties } = require('svg-path-properties');
const LAYERS = ['surface', 'dash', 'ref', 'ghost', 'track', 'wind', 'arrows', 'dots', 'planes'];
const R = 7; // marker radius
const NOTE_DIST = 26; // farther than this from anything drawn = a general note (no marker)

// Overrides after review: id -> { index: [x, y] | 0 }
const SIX = { 0: [90, 58], 1: [230, 58], 2: [90, 128], 3: [160, 128], 4: [230, 128] };
const OVERRIDES = {
  'normal-landing': { 1: [180, 127], 3: 0 },
  'soft-takeoff': { 0: [228, 103], 1: [60, 150], 2: [97, 124] },
  'lazy-eight': { 1: [300, 85], 5: 0 },
  'slow-flight': { 0: [60, 72] },
  'spin-awareness': { 0: [140, 16] },
  'me-critical': { 0: [136, 21], 1: [195, 21] },
  // Instrument panels: the number sits inside each instrument.
  'ir-flight': { ...SIX, 5: [160, 98], 6: 0 },
  'me-oei-instruments': { ...SIX, 5: [160, 98], 6: 0 },
  'ir-partial': { ...SIX, 5: [160, 58], 6: 0 },
};

function samples(d) {
  const pts = [];
  for (const k of LAYERS) {
    if (!d[k]) continue;
    for (const sub of d[k].split(/(?=M)/)) {
      try {
        const p = new svgPathProperties(sub);
        const len = p.getTotalLength();
        for (let s = 0; s <= len; s += 2) { const q = p.getPointAtLength(s); pts.push([q.x, q.y]); }
      } catch { /* skip bad subpath */ }
    }
  }
  return pts;
}
const distToBox = ([x, y], [x0, y0, x1, y1]) => Math.hypot(Math.max(x0 - x, 0, x - x1), Math.max(y0 - y, 0, y - y1));
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

const out = {};
for (const id of ALL_IDS) {
  const d = DIAG[id]();
  const pts = samples(d);
  const placed = [];
  out[id] = mergeLabels(d).map((m, i) => {
    const ov = OVERRIDES[id]?.[i];
    if (ov !== undefined) { if (ov) placed.push(ov); return ov; }
    const [x0, y0, x1, y1] = m.box;
    let best = null, bd = Infinity;
    for (const p of pts) { const dd = distToBox(p, m.box); if (dd < bd) { bd = dd; best = p; } }
    if (!best || bd > NOTE_DIST) return 0;
    // Step from the feature toward the label's old spot, so the marker sits beside the line.
    const cx = clamp(best[0], x0, x1), cy = clamp(best[1], y0, y1);
    let dx = cx - best[0], dy = cy - best[1], len = Math.hypot(dx, dy);
    if (len < 1) { dx = 0; dy = -1; len = 1; }
    let at = [best[0] + (dx / len) * (R + 3), best[1] + (dy / len) * (R + 3)];
    // Keep clear of other markers and inside the picture.
    for (let k = 0; k < 12 && placed.some((q) => Math.hypot(q[0] - at[0], q[1] - at[1]) < 2 * R + 2); k++) {
      at = [at[0] + (dx / len) * 6 + (k % 2 ? 6 : -6) * (dy / len), at[1] + (dy / len) * 6 + (k % 2 ? -6 : 6) * (dx / len)];
    }
    at = [Math.round(clamp(at[0], R + 1, 320 - R - 1)), Math.round(clamp(at[1], R + 1, 170 - R - 1))];
    placed.push(at);
    return at;
  });
}
const body = Object.entries(out).map(([id, v]) => `  '${id}': ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(new URL('../src/library/callout-positions.js', import.meta.url),
  `// GENERATED by scripts/place-callouts.mjs, then reviewed. Marker position per callout\n// ([x, y] in the 320×170 picture), or 0 for a note listed below the picture with no marker.\nexport const CALLOUT_POS = {\n${body}\n};\n`);
console.log('placed', Object.keys(out).length);
